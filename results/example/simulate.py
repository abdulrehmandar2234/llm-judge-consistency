"""Fabricate a runs.jsonl so the analysis pipeline can be demonstrated offline.

    THIS SCRIPT INVENTS DATA. NOTHING IT PRODUCES IS A MEASUREMENT.

No model is called. Rankings are generated by perturbing an arbitrary reference
order with a fixed number of adjacent swaps per condition, which means every
number downstream is a property of the swap counts chosen below and of nothing
else. The "agreement" it reports is arithmetic on noise I picked.

It exists for one reason: so that someone reading the repository can see the
shape of the output — the summary table, the three charts, the metrics file —
without an API key and without spending anything. It is the plumbing being
demonstrated, not a result.

Anything real must come from:

    python src/rank.py && python src/evaluate.py && python src/plots.py

which writes to results/ (not results/example/) from actual API responses.

Usage:
    python results/example/simulate.py
"""

import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "results" / "example"

SEED = 7

# Adjacent swaps applied per replicate, per condition. These are invented.
# They are ordered to reflect what the README predicts in advance -- which is
# exactly why the output must never be read as evidence for those predictions.
SWAPS = {
    "base": 3,
    "shuffled": 7,
    "temp07": 5,
    "variant_b": 4,
}
REPLICATES = 5


def perturb(order, n_swaps, rng):
    out = list(order)
    for _ in range(n_swaps):
        i = rng.randrange(len(out) - 1)
        out[i], out[i + 1] = out[i + 1], out[i]
    return out


def main():
    candidates = json.loads((ROOT / "data" / "candidates.json").read_text())
    jobs = json.loads((ROOT / "data" / "jobs.json").read_text())
    ids = [c["id"] for c in candidates]

    rng = random.Random(SEED)
    lines = []

    for job in jobs:
        # An arbitrary "reference" ordering for this job. Not a judgement.
        reference = list(ids)
        rng.shuffle(reference)

        for condition, n_swaps in SWAPS.items():
            for rep in range(REPLICATES):
                ranking = perturb(reference, n_swaps, rng)

                presentation = list(ids)
                if condition == "shuffled":
                    order_rng = random.Random(1000 + rep)
                    order_rng.shuffle(presentation)

                lines.append(json.dumps({
                    "job_id": job["id"],
                    "condition": condition,
                    "replicate": rep,
                    "model": "SIMULATED-no-model-was-called",
                    "temperature": 0.7 if condition == "temp07" else 0.0,
                    "prompt_variant": "b" if condition == "variant_b" else "a",
                    "presentation_order": presentation,
                    "ranking": ranking,
                    "scores": {c: float(100 - ranking.index(c) * 3) for c in ids},
                    "issues": [],
                    "latency_s": 0.0,
                    "usage": {"prompt_tokens": 0, "completion_tokens": 0},
                    "ts": "1970-01-01T00:00:00+00:00",
                    "SIMULATED": True,
                }))

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "runs.jsonl").write_text("\n".join(lines) + "\n")
    print(f"wrote {len(lines)} FABRICATED runs to {OUT / 'runs.jsonl'}")
    print("these are not measurements -- see the docstring at the top of this file")


if __name__ == "__main__":
    main()
